-- One row per subaward report: a prime contractor or grantee passing part of the work on.
select
    subaward_key,
    kind,
    subaward_number,
    try_cast(subaward_amount as double) as subaward_amount,
    try_cast(subaward_action_date as date) as subaward_action_date,
    cast(fiscal_year as integer) as fiscal_year,
    subawardee_uei,
    upper(subawardee_name) as subawardee_name,
    subawardee_parent_name,
    subawardee_city,
    subawardee_state,
    coalesce(subawardee_state = 'VI', false) as is_local_subawardee,
    subawardee_business_types,
    sub_pop_city,
    subaward_description,
    prime_award_key,
    try_cast(prime_award_amount as double) as prime_award_amount,
    prime_awardee_uei,
    upper(prime_awardee_name) as prime_awardee_name,
    prime_awardee_state,
    prime_awarding_agency,
    prime_awarding_sub_agency,
    try_cast(prime_end_date as date) as prime_end_date,
    prime_naics_code,
    prime_naics_description,
    prime_description,
    permalink
from {{ source('raw', 'subawards') }}
